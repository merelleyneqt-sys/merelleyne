#!/usr/bin/env python3
"""Rebuild tracks.js from tracks.json + audio/*.mp3 (adds duration and waveform peaks).

Usage: python3 scripts/build_tracks.py
Edit tracks.json (title, key, bpm, price, buy link), drop the mp3 into audio/, run this.
"""
import json, subprocess, struct, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
BINS = 64

def peaks(path):
    raw = subprocess.run(
        ["ffmpeg", "-loglevel", "error", "-i", str(path), "-ac", "1", "-ar", "4000",
         "-f", "s16le", "-"], capture_output=True, check=True).stdout
    n = len(raw) // 2
    samples = struct.unpack(f"<{n}h", raw[: n * 2])
    step = max(1, n // BINS)
    out = []
    for i in range(BINS):
        chunk = samples[i * step:(i + 1) * step] or [0]
        rms = (sum(s * s for s in chunk) / len(chunk)) ** 0.5
        out.append(rms)
    top = max(out) or 1
    return [round(v / top, 2) for v in out], n / 4000

tracks = json.loads((ROOT / "tracks.json").read_text())
for t in tracks:
    t["peaks"], t["duration"] = peaks(ROOT / "audio" / t["file"])
    t["duration"] = round(t["duration"])

(ROOT / "tracks.js").write_text(
    "// Generated by scripts/build_tracks.py — edit tracks.json instead.\n"
    "window.TRACKS = " + json.dumps(tracks, ensure_ascii=False) + ";\n")
print(f"{len(tracks)} tracks written")
