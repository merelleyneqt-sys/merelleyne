#!/usr/bin/env python3
"""Rebuild tracks.js from tracks.json + audio/*.mp3 (adds duration).

Usage: python3 scripts/build_tracks.py
Edit tracks.json (title, key, bpm), drop the mp3 into audio/, run this.
"""
import json, subprocess, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
def duration(path):
    out = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration",
                          "-of", "csv=p=0", str(path)], capture_output=True, check=True, text=True).stdout
    return round(float(out))

tracks = json.loads((ROOT / "tracks.json").read_text())
for t in tracks:
    t["duration"] = duration(ROOT / "audio" / t["file"])
    t.pop("peaks", None)

(ROOT / "tracks.js").write_text(
    "// Generated by scripts/build_tracks.py — edit tracks.json instead.\n"
    "window.TRACKS = " + json.dumps(tracks, ensure_ascii=False) + ";\n")
print(f"{len(tracks)} tracks written")
